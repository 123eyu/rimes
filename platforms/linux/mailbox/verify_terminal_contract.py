#!/usr/bin/env python3
"""Import/check actual AppKit + SwiftTerm terminal behavior and render provenance."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
HERE = Path(__file__).resolve().parent
SOURCES = [f'Sources/RimeBuffer/Mailbox/{name}.swift' for name in
           ['MailboxTerminalWorkspace', 'MailboxAdaptiveSplitView', 'MailboxWorkspaceUI',
            'MailboxTerminalLinuxFixtures']]
SOURCES += ['Sources/RimeBuffer/CodexSession/CodexProcessEnvironment.swift']
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--import-fixture', type=Path)
parser.add_argument('--output', type=Path)
args = parser.parse_args()
destination = HERE / 'resources/native-terminal.json'
value = json.loads((args.import_fixture or destination).read_text())
expected = {name: hashlib.sha256((ROOT / name).read_bytes()).hexdigest() for name in SOURCES}
if value.get('purpose') != 'public-mailbox-terminal-contract' or value.get('schemaVersion') != 1 or value.get('sources') != expected:
    raise SystemExit('Re-export and review the native Mailbox terminal contract')
if args.import_fixture:
    temporary = destination.with_suffix('.json.edit')
    temporary.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n')
    temporary.replace(destination)
if args.output:
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('// Generated by verify_terminal_contract.py.\n#pragma once\n'
                          'namespace rimes::native { inline constexpr char kTerminalContract[] = R"terminal('
                          + json.dumps(value, ensure_ascii=False, sort_keys=True) + ')terminal"; }\n')
print('Native Mailbox terminal geometry, file limits and source contract is current')
