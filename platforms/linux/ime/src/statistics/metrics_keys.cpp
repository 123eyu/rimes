#include "metrics_service.hpp"
#include <linux/input-event-codes.h>
#include <map>

namespace fcitx {
std::string MetricsKeyID(const Key& key) {
    // Fcitx frontends use XKB codes (evdev + 8), including Wayland v2:
    // https://github.com/fcitx/fcitx5/blob/5.1.7/src/frontend/waylandim/waylandimserverv2.cpp#L419
    // Prefer position over the translated symbol, so shifted and alternative
    // layouts do not move a physical key to a different heatmap cell.
    static const std::map<int, std::string> physical = {{KEY_A, "KeyA"},
                                                        {KEY_B, "KeyB"},
                                                        {KEY_C, "KeyC"},
                                                        {KEY_D, "KeyD"},
                                                        {KEY_E, "KeyE"},
                                                        {KEY_F, "KeyF"},
                                                        {KEY_G, "KeyG"},
                                                        {KEY_H, "KeyH"},
                                                        {KEY_I, "KeyI"},
                                                        {KEY_J, "KeyJ"},
                                                        {KEY_K, "KeyK"},
                                                        {KEY_L, "KeyL"},
                                                        {KEY_M, "KeyM"},
                                                        {KEY_N, "KeyN"},
                                                        {KEY_O, "KeyO"},
                                                        {KEY_P, "KeyP"},
                                                        {KEY_Q, "KeyQ"},
                                                        {KEY_R, "KeyR"},
                                                        {KEY_S, "KeyS"},
                                                        {KEY_T, "KeyT"},
                                                        {KEY_U, "KeyU"},
                                                        {KEY_V, "KeyV"},
                                                        {KEY_W, "KeyW"},
                                                        {KEY_X, "KeyX"},
                                                        {KEY_Y, "KeyY"},
                                                        {KEY_Z, "KeyZ"},
                                                        {KEY_0, "Digit0"},
                                                        {KEY_1, "Digit1"},
                                                        {KEY_2, "Digit2"},
                                                        {KEY_3, "Digit3"},
                                                        {KEY_4, "Digit4"},
                                                        {KEY_5, "Digit5"},
                                                        {KEY_6, "Digit6"},
                                                        {KEY_7, "Digit7"},
                                                        {KEY_8, "Digit8"},
                                                        {KEY_9, "Digit9"},
                                                        {KEY_ESC, "Escape"},
                                                        {KEY_SPACE, "Space"},
                                                        {KEY_TAB, "Tab"},
                                                        {KEY_ENTER, "Enter"},
                                                        {KEY_BACKSPACE, "Backspace"},
                                                        {KEY_DELETE, "ForwardDelete"},
                                                        {KEY_HOME, "Home"},
                                                        {KEY_END, "End"},
                                                        {KEY_PAGEUP, "PageUp"},
                                                        {KEY_PAGEDOWN, "PageDown"},
                                                        {KEY_LEFT, "ArrowLeft"},
                                                        {KEY_RIGHT, "ArrowRight"},
                                                        {KEY_UP, "ArrowUp"},
                                                        {KEY_DOWN, "ArrowDown"},
                                                        {KEY_LEFTSHIFT, "LeftShift"},
                                                        {KEY_RIGHTSHIFT, "RightShift"},
                                                        {KEY_LEFTCTRL, "LeftControl"},
                                                        {KEY_RIGHTCTRL, "RightControl"},
                                                        {KEY_LEFTALT, "LeftOption"},
                                                        {KEY_RIGHTALT, "RightOption"},
                                                        {KEY_LEFTMETA, "LeftCommand"},
                                                        {KEY_RIGHTMETA, "RightCommand"},
                                                        {KEY_CAPSLOCK, "CapsLock"},
                                                        {KEY_FN, "Function"},
                                                        {KEY_GRAVE, "Backquote"},
                                                        {KEY_MINUS, "Minus"},
                                                        {KEY_EQUAL, "Equal"},
                                                        {KEY_LEFTBRACE, "BracketLeft"},
                                                        {KEY_RIGHTBRACE, "BracketRight"},
                                                        {KEY_BACKSLASH, "Backslash"},
                                                        {KEY_SEMICOLON, "Semicolon"},
                                                        {KEY_APOSTROPHE, "Quote"},
                                                        {KEY_COMMA, "Comma"},
                                                        {KEY_DOT, "Period"},
                                                        {KEY_SLASH, "Slash"},
                                                        {KEY_F1, "F1"},
                                                        {KEY_F2, "F2"},
                                                        {KEY_F3, "F3"},
                                                        {KEY_F4, "F4"},
                                                        {KEY_F5, "F5"},
                                                        {KEY_F6, "F6"},
                                                        {KEY_F7, "F7"},
                                                        {KEY_F8, "F8"},
                                                        {KEY_F9, "F9"},
                                                        {KEY_F10, "F10"},
                                                        {KEY_F11, "F11"},
                                                        {KEY_F12, "F12"},
                                                        {KEY_F13, "F13"},
                                                        {KEY_F14, "F14"},
                                                        {KEY_F15, "F15"},
                                                        {KEY_F16, "F16"},
                                                        {KEY_F17, "F17"},
                                                        {KEY_KP0, "Numpad0"},
                                                        {KEY_KP1, "Numpad1"},
                                                        {KEY_KP2, "Numpad2"},
                                                        {KEY_KP3, "Numpad3"},
                                                        {KEY_KP4, "Numpad4"},
                                                        {KEY_KP5, "Numpad5"},
                                                        {KEY_KP6, "Numpad6"},
                                                        {KEY_KP7, "Numpad7"},
                                                        {KEY_KP8, "Numpad8"},
                                                        {KEY_KP9, "Numpad9"},
                                                        {KEY_KPDOT, "NumpadDecimal"},
                                                        {KEY_KPENTER, "NumpadEnter"},
                                                        {KEY_KPMINUS, "NumpadSubtract"},
                                                        {KEY_KPPLUS, "NumpadAdd"},
                                                        {KEY_KPASTERISK, "NumpadMultiply"},
                                                        {KEY_KPSLASH, "NumpadDivide"},
                                                        {KEY_KPEQUAL, "NumpadEqual"}};
    if (key.code()) {
        const auto found = physical.find(key.code() - 8);
        return found == physical.end() ? std::string() : found->second;
    }
    // Some protocol/test frontends provide no physical code. Only canonical
    // key symbols are admitted; never serialize arbitrary characters as IDs.
    const auto symbol = key.sym();
    if (symbol >= FcitxKey_a && symbol <= FcitxKey_z)
        return "Key" + std::string(1, char(symbol - FcitxKey_a + 'A'));
    if (symbol >= FcitxKey_A && symbol <= FcitxKey_Z)
        return "Key" + std::string(1, char(symbol));
    if (symbol >= FcitxKey_0 && symbol <= FcitxKey_9)
        return "Digit" + std::string(1, char(symbol));
    if (symbol >= FcitxKey_F1 && symbol <= FcitxKey_F17)
        return "F" + std::to_string(symbol - FcitxKey_F1 + 1);
    static const std::map<KeySym, std::string> symbols = {{FcitxKey_space, "Space"},
                                                          {FcitxKey_Return, "Enter"},
                                                          {FcitxKey_Tab, "Tab"},
                                                          {FcitxKey_BackSpace, "Backspace"},
                                                          {FcitxKey_Delete, "ForwardDelete"},
                                                          {FcitxKey_Escape, "Escape"},
                                                          {FcitxKey_Left, "ArrowLeft"},
                                                          {FcitxKey_Right, "ArrowRight"},
                                                          {FcitxKey_Up, "ArrowUp"},
                                                          {FcitxKey_Down, "ArrowDown"},
                                                          {FcitxKey_Home, "Home"},
                                                          {FcitxKey_End, "End"},
                                                          {FcitxKey_Page_Up, "PageUp"},
                                                          {FcitxKey_Page_Down, "PageDown"},
                                                          {FcitxKey_Shift_L, "LeftShift"},
                                                          {FcitxKey_Shift_R, "RightShift"},
                                                          {FcitxKey_Control_L, "LeftControl"},
                                                          {FcitxKey_Control_R, "RightControl"},
                                                          {FcitxKey_Alt_L, "LeftOption"},
                                                          {FcitxKey_Alt_R, "RightOption"},
                                                          {FcitxKey_Super_L, "LeftCommand"},
                                                          {FcitxKey_Super_R, "RightCommand"},
                                                          {FcitxKey_Caps_Lock, "CapsLock"},
                                                          {FcitxKey_grave, "Backquote"},
                                                          {FcitxKey_minus, "Minus"},
                                                          {FcitxKey_equal, "Equal"},
                                                          {FcitxKey_bracketleft, "BracketLeft"},
                                                          {FcitxKey_bracketright, "BracketRight"},
                                                          {FcitxKey_backslash, "Backslash"},
                                                          {FcitxKey_semicolon, "Semicolon"},
                                                          {FcitxKey_apostrophe, "Quote"},
                                                          {FcitxKey_comma, "Comma"},
                                                          {FcitxKey_period, "Period"},
                                                          {FcitxKey_slash, "Slash"}};
    const auto found = symbols.find(symbol);
    return found == symbols.end() ? std::string() : found->second;
}
} // namespace fcitx
